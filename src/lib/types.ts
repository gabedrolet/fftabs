/** Shapes of the JSON files in data/ (see PLAN.md §2). */

export const PARTS = ['guitar', 'bass', 'drums', 'lyrics'] as const;
export type Part = (typeof PARTS)[number];

export const PART_LABEL: Record<Part, string> = {
  guitar: 'Guitar',
  bass: 'Bass',
  drums: 'Drums',
  lyrics: 'Lyrics',
};

export function isPart(value: string | undefined): value is Part {
  return value !== undefined && (PARTS as readonly string[]).includes(value);
}

export type AlbumKind = 'studio' | 'live' | 'compilation' | 'collection' | 'side-project';

export type Counts = { tracks: number } & Record<Part, number>;

/** One entry of data/index.json → albums */
export interface AlbumSummary {
  id: string;
  title: string;
  kind: AlbumKind;
  year?: number;
  cover?: string;
  lyricsSheet?: string;
  counts: Counts;
}

/** One entry of data/index.json → search: [title, albumId, trackId, parts] */
export type SearchEntry = [title: string, albumId: string, trackId: string, parts: Part[]];

/** data/index.json (generated by tools/build_index.py) */
export interface CatalogIndex {
  generated: string;
  albums: AlbumSummary[];
  search: SearchEntry[];
}

/** One track in data/albums/album_<id>.json */
export interface Track {
  id: string;
  title: string;
  n?: number;
  disc?: number;
  note?: string;
  bonus?: boolean;
  /** compilation tracks: id of the original album */
  from?: string;
}

/** data/albums/album_<id>.json */
export interface Album {
  id: string;
  title: string;
  kind: AlbumKind;
  year?: number;
  released?: string;
  label?: string;
  billboard?: string;
  cover?: string;
  description?: string;
  lyricsSheet?: string;
  tracks: Track[];
}

/** A path, or several versions of the same song */
export type FileRef = string | string[];
export type TrackFiles = Record<string, FileRef>;

/** data/<part>/<part>_<id>.json */
export interface PartFile {
  album: string;
  instrument: Part;
  tabs?: TrackFiles;
  lyrics?: TrackFiles;
}

/** An album with its instrument files loaded */
export interface LoadedAlbum {
  summary: AlbumSummary;
  album: Album;
  parts: Partial<Record<Part, TrackFiles>>;
}
